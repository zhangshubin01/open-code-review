# Collect a full Android Lint report into Markdown for the review background.
#
#   ./scripts/collect-lint-report.sh                  # run ./gradlew lint, then read every report it writes
#   ./scripts/collect-lint-report.sh <report.xml> ... # read the given report(s) instead of running lint
#
# The report is the deterministic half of the review: every error and warning
# lint found, grouped by file, so the model can match against it instead of
# re-discovering what lint already reported. Information/Ignore findings are
# dropped. Override the Gradle task with OCR_LINT_ARGS (e.g. "lintDebug").

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

# This script lives at <repo>/scripts/, so the report is written to <repo>/.ocr/.
OUT="${OCR_LINT_OUT:-$SCRIPT_DIR/../.ocr/lint-report.md}"
read -ra LINT_ARGS <<< "${OCR_LINT_ARGS:-lint}"

REPORTS=("$@")
AUTO=false
[[ ${#REPORTS[@]} -gt 0 ]] || AUTO=true

find_repo_root() {
  local dir="$SCRIPT_DIR"
  while [[ "$dir" != "/" ]]; do
    if [[ -x "$dir/gradlew" ]]; then
      printf '%s\n' "$dir"
      return 0
    fi
    dir="$(dirname "$dir")"
  done
  return 1
}

if $AUTO; then
  REPO_ROOT="$(find_repo_root)" || {
    echo "error: could not find gradlew above $SCRIPT_DIR -- run from inside an Android repo" >&2
    exit 2
  }
  echo "running: ./gradlew ${LINT_ARGS[*]}  (in $REPO_ROOT)" >&2
  (cd "$REPO_ROOT" && ./gradlew "${LINT_ARGS[@]}")

  while IFS= read -r report; do
    [[ -n "$report" ]] && REPORTS+=("$report")
  done < <(cd "$REPO_ROOT" && find . -name 'lint-results-*.xml' ! -name '*-fatal.xml' -print 2>/dev/null | grep '/build/reports/' | sed 's|^\./||' | sort)
  RUN_DIR="$REPO_ROOT"
else
  RUN_DIR="."
fi

if [[ ${#REPORTS[@]} -eq 0 ]]; then
  echo "error: no lint-results-*.xml found under */build/reports/" >&2
  echo "  run ./gradlew lint first, or pass a report path explicitly:" >&2
  echo "    $0 app/build/reports/lint-results-debug.xml" >&2
  exit 2
fi

for report in "${REPORTS[@]}"; do
  if [[ ! -f "$RUN_DIR/$report" ]]; then
    echo "error: $report not found" >&2
    exit 2
  fi
done

mkdir -p "$(dirname "$OUT")"

cd "$RUN_DIR"
python3 - "$OUT" "${REPORTS[@]}" <<'PY'
import sys
import xml.etree.ElementTree as ET
from collections import defaultdict
from datetime import date

out = sys.argv[1]
reports = sys.argv[2:]

# The report keeps what the reviewer is asked to combine with: errors and
# warnings. Information and Ignore are dropped.
KEPT_SEVERITIES = {"Error", "Fatal", "Warning"}


def cell(text):
    return text.replace("|", "\\|").replace("\n", " ").strip()


def sort_key(value):
    # Locations without a line sort after everything that has one.
    try:
        return (0, int(value))
    except ValueError:
        return (1, str(value))


findings = []  # (file, severity, issue_id, message, line)
for report in reports:
    try:
        root = ET.parse(report).getroot()
    except (ET.ParseError, OSError) as exc:
        sys.exit(f"error: could not parse {report}: {exc}")
    for issue in root.iter("issue"):
        severity = issue.get("severity", "")
        if severity not in KEPT_SEVERITIES:
            continue
        issue_id = issue.get("id", "?")
        message = cell(issue.get("message", ""))
        for loc in issue.iter("location"):
            path = loc.get("file")
            if not path:
                continue
            findings.append((path, severity, issue_id, message, loc.get("line") or "?"))

# Deduplicate identical findings and merge their line numbers.
grouped = defaultdict(list)
for path, severity, issue_id, message, line in findings:
    grouped[(path, severity, issue_id, message)].append(line)

errors = sum(1 for k in grouped if k[1] in ("Error", "Fatal"))
warnings = sum(1 for k in grouped if k[1] == "Warning")
files = {k[0] for k in grouped}

body = [
    "# Android Lint Report",
    "",
    f"Generated by scripts/collect-lint-report.sh on {date.today().isoformat()}.",
    f"Source: {', '.join(reports)}.",
    f"Total: {errors} error(s), {warnings} warning(s) across {len(files)} file(s).",
]

for path in sorted(files):
    body.append("")
    body.append(f"## {path}")
    body.append("")
    entries = [(k, v) for k, v in grouped.items() if k[0] == path]
    entries.sort(key=lambda kv: (sort_key(min(kv[1], key=sort_key)), kv[0][2]))
    for key, locations in entries:
        _, severity, issue_id, message = key
        label = "Error" if severity in ("Error", "Fatal") else "Warning"
        where = ", ".join(str(l) for l in sorted(set(locations), key=sort_key))
        body.append(f"- [{label}] {issue_id}: {message} (line {where})")

body.append("")

with open(out, "w", encoding="utf-8") as fh:
    fh.write("\n".join(body))

print(f"wrote {out}: {errors} error(s), {warnings} warning(s) across {len(files)} file(s)")
PY
